#' Load Filtered and Raw 10x Genomics Count Matrices
#'
#' Batch loads 10x Genomics formatted sparse matrices (matrix, features, and barcodes)
#' for multiple samples. It simultaneously reads both the 'filtered' (cell-containing)
#' and 'raw' (all droplets) outputs from Cell Ranger using Seurat's \code{ReadMtx}.
#' Loading both matrices is highly useful for downstream ambient RNA decontamination
#' workflows (such as SoupX) that require the empty droplet background to estimate
#' the ambient RNA profile. Includes a progress bar to track loading status.
#'
#' @param sample_names Character vector. A list of sample identifiers corresponding to the folder prefixes (e.g., as generated by \code{get_sample_names()}).
#' @param filtered_dir Character. The parent directory path containing the \code{"*_filtered_feature_bc_matrix"} folders.
#' @param raw_dir Character. The parent directory path containing the \code{"*_raw_feature_bc_matrix"} folders.
#'
#' @return A named list containing two top-level elements:
#' \itemize{
#'   \item \code{filtered}: A named list of the filtered sparse count matrices (\code{dgCMatrix}) for each sample.
#'   \item \code{raw}: A named list of the raw sparse count matrices (\code{dgCMatrix}) for each sample.
#' }
#'
#' @export
#'
#' @examples
#' \dontrun{
#' # 1. Extract sample names using your helper function
#' my_samples <- get_sample_names(filtered_dir = "data/filtered_outputs")
#'
#' # 2. Load both raw and filtered matrices for all samples
#' counts_list <- load_counts(
#'   sample_names = my_samples,
#'   filtered_dir = "data/filtered_outputs",
#'   raw_dir = "data/raw_outputs"
#' )
#'
#' # 3. Access the matrices for the first sample to pass into SoupX
#' patient1_filt <- counts_list$filtered[["Patient1"]]
#' patient1_raw  <- counts_list$raw[["Patient1"]]
#'
#' # Check dimensions
#' dim(patient1_filt)
#' dim(patient1_raw)
#' }
load_counts <- function(sample_names, filtered_dir, raw_dir) {
  cts_filtered_list <- list()
  cts_raw_list <- list()

  cat("Loading counts:\n")
  pb <- txtProgressBar(min = 0, max = length(sample_names), style = 3)

  for (i in seq_along(sample_names)) {
    sample_name <- sample_names[i]
    filtered_path <- file.path(filtered_dir, paste0(sample_name, "_filtered_feature_bc_matrix"))
    raw_path <- file.path(raw_dir, paste0(sample_name, "_raw_feature_bc_matrix"))

    cts_filtered <- ReadMtx(
      mtx = paste0(filtered_path, '/matrix.mtx.gz'),
      features = paste0(filtered_path, "/features.tsv.gz"),
      cells = paste0(filtered_path, "/barcodes.tsv.gz")
    )

    cts_raw <- ReadMtx(
      mtx = paste0(raw_path, '/matrix.mtx.gz'),
      features = paste0(raw_path, "/features.tsv.gz"),
      cells = paste0(raw_path, "/barcodes.tsv.gz")
    )

    cts_filtered_list[[sample_name]] <- cts_filtered
    cts_raw_list[[sample_name]] <- cts_raw

    setTxtProgressBar(pb, i)
  }
  close(pb)
  return(list(filtered = cts_filtered_list, raw = cts_raw_list))
}

