#' Run End-to-End Preparation Pipeline for SoupX Decontamination
#'
#' Acts as a master wrapper to execute the entire data loading and preparation phase
#' for ambient RNA removal. It automatically extracts sample names from the directory
#' structure, loads both raw and filtered Cell Ranger matrices, initializes the
#' \code{SoupChannel} objects, and runs a rapid Seurat clustering pipeline. The output
#' is a comprehensive bundled list containing all the necessary objects to feed directly
#' into the final contamination estimation and correction steps.
#'
#' @param filtered_dir Character. The file path to the parent directory containing the Cell Ranger \code{"*_filtered_feature_bc_matrix"} folders.
#' @param raw_dir Character. The file path to the parent directory containing the Cell Ranger \code{"*_raw_feature_bc_matrix"} folders.
#' @param manual_contam Character vector. An optional list of specific sample names that will later require a manual contamination override (e.g., adding an artificial penalty to the estimated rho). Default is \code{NULL} (which evaluates to an empty list).
#'
#' @return A structured, named list containing five top-level elements:
#' \itemize{
#'   \item \code{sample_names}: A character vector of the extracted sample identifiers.
#'   \item \code{counts_lists}: A list containing both \code{raw} and \code{filtered} sparse count matrices.
#'   \item \code{soup_list}: A list of initialized \code{SoupChannel} objects.
#'   \item \code{seurat_for_clustering}: A list of processed \code{Seurat} objects with high-resolution clusters stored in their active identities.
#'   \item \code{manual_contam}: The forwarded list of samples designated for manual overrides.
#' }
#'
#' @export
#'
#' @examples
#' \dontrun{
#' # Run the entire preparation pipeline in one line
#' soupx_prep_data <- prepare_soupx_inputs(
#'   filtered_dir = "data/cellranger/filtered",
#'   raw_dir = "data/cellranger/raw",
#'   manual_contam = c("Patient_3") # Flag this patient for manual adjustment later
#' )
#'
#' # Feed the bundled output directly into your estimation function
#' clean_data <- estimate_contamination(
#'   soup_list = soupx_prep_data$soup_list,
#'   seurat_list = soupx_prep_data$seurat_for_clustering,
#'   cts_filtered_list = soupx_prep_data$counts_lists$filtered,
#'   sample_names = soupx_prep_data$sample_names,
#'   manual_contam = soupx_prep_data$manual_contam,
#'   mulFac = 5,
#'   manual = TRUE
#' )
#' }
prepare_soupx_inputs <- function(filtered_dir, raw_dir, manual_contam = NULL) {
  sample_names <- get_sample_names(filtered_dir)

  counts_lists <- load_counts(sample_names, filtered_dir, raw_dir)

  soup_list <- create_soup_channels(counts_lists$raw, counts_lists$filtered, sample_names)

  seurat_for_clustering <- create_seurat_for_clustering(counts_lists$filtered, sample_names)

  # If manual_contam is NULL, default to empty list
  if (is.null(manual_contam)) {
    manual_contam <- list()
  }

  return(list(
    sample_names = sample_names,
    counts_lists = counts_lists,
    soup_list = soup_list,
    seurat_for_clustering = seurat_for_clustering,
    manual_contam = manual_contam
  ))
}


