#' Generate Initial Seurat Clustering for SoupX Estimation
#'
#' Batch processes a list of filtered count matrices through a rapid, standard Seurat
#' pipeline (LogNormalization, Variable Feature selection, Scaling, PCA, Neighborhood
#' Graph construction, Clustering, and UMAP). The primary purpose of this function is
#' to quickly generate the high-resolution clusters (defaulting to \code{resolution = 1.8})
#' required by SoupX. Over-clustering at this stage is highly recommended for accurate
#' ambient RNA profiling via \code{SoupX::autoEstCont()}.
#'
#' @param cts_filtered_list A named list of filtered sparse count matrices, typically generated by the \code{filtered} element of \code{load_counts()}.
#' @param sample_names Character vector. A list of sample identifiers used as keys to match the matrices in the list and assign project names to the Seurat objects.
#'
#' @return A named list of processed \code{Seurat} objects. Each object contains a standard PCA, UMAP embedding, and high-resolution cluster identities stored in the active \code{Idents}.
#'
#' @export
#'
#' @examples
#' \dontrun{
#' # Assuming you have already loaded your filtered matrices
#' counts_list <- load_counts(my_samples, "data/filtered", "data/raw")
#'
#' # Quickly cluster all samples to prepare them for SoupX
#' initial_seurat_list <- create_seurat_for_clustering(
#'   cts_filtered_list = counts_list$filtered,
#'   sample_names = my_samples
#' )
#'
#' # The clusters from these objects can now be extracted and fed into SoupChannels
#' # e.g., soup_channels[[1]] <- setClusters(soup_channels[[1]],
#' # initial_seurat_list[[1]]$seurat_clusters)
#' }
create_seurat_for_clustering <- function(cts_filtered_list, sample_names) {
  seurat_list <- list()
  cat("Clustering for SoupX (Seurat pipeline):\n")
  pb <- txtProgressBar(min = 0, max = length(sample_names), style = 3)

  for (i in seq_along(sample_names)) {
    sample_name <- sample_names[i]
    seurat_temp <- CreateSeuratObject(counts = cts_filtered_list[[sample_name]], project = sample_name)
    seurat_temp <- NormalizeData(seurat_temp)
    seurat_temp <- FindVariableFeatures(seurat_temp)
    seurat_temp <- ScaleData(seurat_temp)
    # seurat_temp <- SCTransform(seurat_temp)
    seurat_temp <- RunPCA(seurat_temp, verbose = FALSE)
    seurat_temp <- FindNeighbors(seurat_temp, dims = 1:50)
    seurat_temp <- FindClusters(seurat_temp, resolution = 1.8)
    seurat_temp <- RunUMAP(seurat_temp, dims = 1:50)

    seurat_list[[sample_name]] <- seurat_temp
    setTxtProgressBar(pb, i)
  }
  close(pb)
  return(seurat_list)
}

