#' Estimate and Remove Ambient RNA Contamination
#'
#' Integrates \code{SoupChannel} objects with initial high-resolution clustering
#' to automatically estimate the ambient RNA contamination fraction (\code{rho})
#' via \code{SoupX::autoEstCont()}. Includes a robust manual override system
#' allowing you to artificially increase the estimated contamination fraction
#' (e.g., adding 5% extra background removal) either globally across all samples
#' or selectively for specific noisy samples. Finally, it applies the chosen
#' correction method to remove the background noise and returns the cleaned count matrices.
#'
#' @param soup_list A named list of \code{SoupChannel} objects, typically generated by \code{create_soup_channels()}.
#' @param seurat_list A named list of clustered \code{Seurat} objects, typically generated by \code{create_seurat_for_clustering()}. Used solely to supply high-resolution cluster identities back to the SoupChannels.
#' @param cts_filtered_list A named list of filtered sparse count matrices. Used to extract the exact cell barcodes to ensure 1:1 mapping with the clusters.
#' @param sample_names Character vector. A list of sample identifiers corresponding to the names in the input lists.
#' @param mulFac Numeric. A percentage to artificially add to the auto-estimated contamination fraction (e.g., \code{mulFac = 5} adds \code{0.05} to the \code{rho} value). Default is 0.
#' @param manual_contam Character vector. A list of specific sample names to apply the \code{mulFac} adjustment to. Only evaluated if \code{manual = TRUE}. Default is an empty list.
#' @param manual Logical. Controls the application of \code{mulFac}. If \code{FALSE}, \code{mulFac} is applied globally to ALL samples. If \code{TRUE}, \code{mulFac} is applied ONLY to the specific samples listed in \code{manual_contam}. Default is FALSE.
#' @param methods Character. The method to use for count adjustment passed to \code{SoupX::adjustCounts()}. Options include "subtraction", "soupOnly", or "multinomial". Default is "subtraction".
#' @param pCut Numeric. The p-value threshold used for identifying cells expressing genes above background levels when \code{methods = "soupOnly"}. Default is 0.01.
#'
#' @return A named list containing two elements:
#' \itemize{
#'   \item \code{soup_list_all}: A list of the updated \code{SoupChannel} objects with their final \code{rho} values calculated and set.
#'   \item \code{corrected_list}: A list of the final, decontaminated sparse count matrices (rounded to integers), ready to be used to create your final Seurat objects.
#' }
#'
#' @export
#'
#' @examples
#' \dontrun{
#' # Assuming soup_channels and seurat_clusters were generated previously
#'
#' # Example 1: Run standard auto-estimation with no manual overrides
#' clean_data <- estimate_contamination(
#'   soup_list = soup_channels,
#'   seurat_list = initial_seurat_objs,
#'   cts_filtered_list = counts_list$filtered,
#'   sample_names = my_samples,
#'   methods = "subtraction"
#' )
#'
#' # Example 2: Sample "Patient_3" looks particularly noisy.
#' # Add an extra 5% (0.05) to its estimated contamination fraction.
#' clean_data_adjusted <- estimate_contamination(
#'   soup_list = soup_channels,
#'   seurat_list = initial_seurat_objs,
#'   cts_filtered_list = counts_list$filtered,
#'   sample_names = my_samples,
#'   mulFac = 5,
#'   manual = TRUE,
#'   manual_contam = c("Patient_3")
#' )
#'
#' # Extract the cleaned matrix for downstream processing
#' p3_clean_matrix <- clean_data_adjusted$corrected_list[["Patient_3"]]
#' }
estimate_contamination <- function(
    soup_list,
    seurat_list,
    cts_filtered_list,
    sample_names,
    mulFac = 0,
    manual_contam = list(),     # character vector of sample names to override
    manual = FALSE,             # if TRUE, apply mulFac to all
    methods = "subtraction",
    pCut = 0.01
) {
  soup_list_all <- list()
  corrected_list <- list()

  cat("Estimating contamination:\n")
  pb <- txtProgressBar(min = 0, max = length(sample_names), style = 3)

  for (i in seq_along(sample_names)) {
    sample_name <- sample_names[i]
    sc <- soup_list[[sample_name]]
    seurat_temp <- seurat_list[[sample_name]]

    # Assign clusters
    clusters <- seurat_temp$seurat_clusters
    names(clusters) <- colnames(cts_filtered_list[[sample_name]])
    sc <- setClusters(sc, clusters)

    # Auto estimate contamination
    sc <- autoEstCont(sc)

    # Extract estimated rho
    estimated_rho <- unique(sc$metaData$rho)
    if (length(estimated_rho) != 1) {
      stop("Sample ", sample_name, ": Expected a single rho value but got: ", paste(estimated_rho, collapse = ", "))
    }
    estimated_rho <- as.numeric(estimated_rho)

    # Determine final contamination fraction
    if (!manual) {
      confrac <- estimated_rho + (mulFac / 100)
      message("Sample: ", sample_name, " | MANUAL mode active | Adjusted rho: ", round(confrac, 4))
    } else {
      if (sample_name %in% manual_contam) {
        confrac <- estimated_rho + (mulFac / 100)
        message("Sample: ", sample_name, " | SELECTIVE manual override | Adjusted rho: ", round(confrac, 4))
      } else {
        confrac <- estimated_rho
        message("Sample: ", sample_name, " | Auto-estimated rho: ", round(confrac, 4))
      }
    }

    # Apply contamination fraction
    sc <- setContaminationFraction(sc, confrac)
    soup_list_all[[sample_name]] <- sc

    # Announce method used
    msg <- paste0("Sample: ", sample_name, " | Adjusting counts using method = '", methods, "'")
    if (methods == "soupOnly") {
      msg <- paste0(msg, " (with pCut = ", pCut, ")")
    }
    message(msg)

    # Adjust counts
    corrected <- adjustCounts(sc, method = methods, pCut = pCut, roundToInt = TRUE)
    corrected_list[[sample_name]] <- corrected

    setTxtProgressBar(pb, i)
  }

  close(pb)

  return(list(
    soup_list_all = soup_list_all,
    corrected_list = corrected_list
  ))
}

