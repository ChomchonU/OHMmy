#' Initialize Final Seurat Objects from Decontaminated Counts
#'
#' Takes a list of fully processed \code{SoupChannel} objects (where the contamination
#' fraction has already been estimated and set), extracts the background-corrected count
#' matrices, and initializes fresh \code{Seurat} objects. During initialization, it applies
#' standard baseline filtering (\code{min.cells = 3}, \code{min.features = 200}) and
#' automatically calculates the mitochondrial read percentage (\code{mitoPercent}) for
#' immediate use in downstream quality control.
#'
#' @param soup_list_all A named list of \code{SoupChannel} objects that have their contamination fraction (\code{rho}) set. Typically the \code{soup_list_all} element returned by \code{estimate_contamination()}.
#' @param sample_names Character vector. A list of sample identifiers used to match the list elements and assign the \code{project} name to each Seurat object.
#'
#' @return A named list of initialized \code{Seurat} objects containing the decontaminated count matrices and a newly appended \code{mitoPercent} metadata column.
#'
#' @export
#'
#' @examples
#' \dontrun{
#' # Assuming clean_data is the list returned by estimate_contamination()
#'
#' final_seurat_list <- create_final_seurat(
#'   soup_list_all = clean_data$soup_list_all,
#'   sample_names = my_samples
#' )
#'
#' # The objects are now ready for standard Seurat QC filtering!
#' patient1_seurat <- final_seurat_list[["Patient_1"]]
#' head(patient1_seurat@meta.data)
#' }
create_final_seurat <- function(soup_list_all, sample_names) {
  final_seurat_list <- list()
  cat("Creating final Seurat objects with corrected counts:\n")
  pb <- txtProgressBar(min = 0, max = length(sample_names), style = 3)

  for (i in seq_along(sample_names)) {
    sample_name <- sample_names[i]
    sc <- soup_list_all[[sample_name]]
    corrected_counts <- adjustCounts(sc, roundToInt = TRUE)

    seurat_ind <- CreateSeuratObject(counts = corrected_counts, project = sample_name, min.cells = 3, min.features = 200)
    seurat_ind$mitoPercent <- PercentageFeatureSet(seurat_ind, pattern = "^MT-")

    final_seurat_list[[sample_name]] <- seurat_ind
    setTxtProgressBar(pb, i)
  }
  close(pb)
  return(final_seurat_list)
}


