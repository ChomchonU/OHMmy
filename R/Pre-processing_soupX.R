#' Update Seurat Object with SoupX-Corrected Counts and Metadata
#'
#' Merges a list of SoupX-processed Seurat objects and seamlessly maps their
#' background-corrected count matrices and updated QC metrics back onto a pre-existing
#' Seurat object. It handles the tedious formatting steps, such as barcode stripping,
#' standardizing mitochondrial column names, and intersecting cells/genes to prevent
#' dimension mismatches. Finally, it replaces the raw counts layer in the original
#' object with the decontaminated data.
#'
#' @param original_seurat A pre-existing \code{Seurat} object that you wish to update with the cleaned counts.
#' @param soupx_seurat_list A named list of \code{Seurat} objects containing SoupX-corrected counts, typically the output of \code{create_final_seurat()}.
#' @param mito_colname Character. The name of the mitochondrial percentage column in the SoupX objects. It will be automatically standardized to \code{"pct_counts_mt"} during the transfer. Default is \code{"mitoPercent"}.
#' @param counts_assay Character. The name of the assay in the original object where the counts layer should be updated. Default is \code{"RNA"}.
#' @param rename_barcodes Logical. If \code{TRUE}, strips the common \code{"-1"} suffix from the barcodes in the merged SoupX object to ensure they match standard Seurat formatting. Default is \code{TRUE}.
#' @param save_path Character. An optional file path (.rds) to automatically save the updated Seurat object to disk. Default is \code{NULL} (does not save).
#'
#' @return An updated \code{Seurat} object containing the decontaminated count matrix and matching QC metadata (\code{nCount_RNA}, \code{nFeature_RNA}, \code{pct_counts_mt}). The object is strictly subsetted to contain only the overlapping valid cells and genes.
#'
#' @export
#'
#' @examples
#' \dontrun{
#' # Assuming 'my_seurat' is an existing object you want to clean,
#' # and 'pipeline_out' is the list returned by process_soupx_samples()
#'
#' cleaned_seurat <- addSoupXMetaToSeurat(
#'   original_seurat = my_seurat,
#'   soupx_seurat_list = pipeline_out$final_seurat,
#'   mito_colname = "mitoPercent",
#'   counts_assay = "RNA",
#'   rename_barcodes = TRUE,
#'   save_path = "Results/Seurat_SoupX_Cleaned.rds"
#' )
#'
#' # The 'cleaned_seurat' object now contains the background-corrected counts
#' # in its RNA assay, ready for standard downstream normalization!
#' }
addSoupXMetaToSeurat <- function(original_seurat,
                                 soupx_seurat_list,
                                 mito_colname = "mitoPercent",
                                 counts_assay = "RNA",
                                 rename_barcodes = TRUE,
                                 save_path = NULL) {
  library(Seurat)

  message("Merging SoupX Seurat objects...")
  merged_seurat <- merge(
    soupx_seurat_list[[1]],
    y = soupx_seurat_list[-1],
    add.cell.ids = names(soupx_seurat_list),
    project = "MergedSoupX"
  )

  if (rename_barcodes) {
    message("Renaming barcodes (removing '-1')...")
    old_barcodes <- colnames(merged_seurat)
    new_barcodes <- gsub("-1$", "", old_barcodes)
    colnames(merged_seurat) <- new_barcodes
  }

  # Standardize mito column name
  if (mito_colname %in% colnames(merged_seurat@meta.data)) {
    colnames(merged_seurat@meta.data)[colnames(merged_seurat@meta.data) == mito_colname] <- "pct_counts_mt"
  }

  message("Transferring metadata (nCount_RNA, nFeature_RNA, pct_counts_mt)...")
  required_cols <- c("nCount_RNA", "nFeature_RNA", "pct_counts_mt")
  missing_cols <- setdiff(required_cols, colnames(merged_seurat@meta.data))
  if (length(missing_cols) > 0) {
    stop("Missing columns in SoupX metadata: ", paste(missing_cols, collapse = ", "))
  }

  # Match metadata by shared barcodes
  matched_cells <- intersect(colnames(original_seurat), rownames(merged_seurat@meta.data))
  if (length(matched_cells) == 0) {
    stop("No overlapping cell barcodes found between original and merged Seurat objects.")
  }

  matched_meta <- merged_seurat@meta.data[matched_cells, required_cols, drop = FALSE]
  updated_seurat <- AddMetaData(original_seurat, metadata = matched_meta)

  message("Joining RNA assay layers in merged object...")
  merged_seurat[[counts_assay]] <- JoinLayers(merged_seurat[[counts_assay]])

  message("Preparing raw count transfer...")
  cells_to_use <- colnames(original_seurat)
  genes_to_use <- rownames(original_seurat[[counts_assay]])

  missing_cells <- setdiff(cells_to_use, colnames(merged_seurat))
  missing_genes <- setdiff(genes_to_use, rownames(merged_seurat[[counts_assay]]))
  if (length(missing_cells) > 0) {
    message(" Warning: Some cells not found in merged object. Subsetting...")
  }

  if (length(missing_genes) > 0) {
    message(" Warning: Some genes not found in merged object. Subsetting...")
  }

  # Subset to only available ones (preserve order)
  valid_cells <- intersect(cells_to_use, colnames(merged_seurat))
  valid_genes <- intersect(genes_to_use, rownames(merged_seurat[[counts_assay]]))

  raw_counts <- GetAssayData(merged_seurat, assay = counts_assay, layer = "counts")[valid_genes, valid_cells, drop = FALSE]

  # Subset the original object to match valid dimensions (if necessary)
  updated_seurat <- subset(updated_seurat, cells = valid_cells, features = valid_genes)

  # Set counts
  updated_seurat[[counts_assay]] <- SetAssayData(
    updated_seurat[[counts_assay]],
    layer = "counts",
    new.data = raw_counts
  )

  if (!is.null(save_path)) {
    message("Saving updated Seurat object to: ", save_path)
    saveRDS(updated_seurat, file = save_path)
  }

  message("Done: Metadata and counts transferred successfully.")
  return(updated_seurat)
}
