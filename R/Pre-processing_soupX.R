#' Execute Final SoupX Contamination Removal and Seurat Initialization
#'
#' The second half of the master ambient RNA removal workflow. It takes the bundled
#' preparation data (generated by \code{prepare_soupx_inputs}), estimates the
#' contamination fractions using the high-resolution clusters, applies any specified
#' manual overrides, and adjusts the count matrices. Finally, it automatically
#' initializes a fresh list of \code{Seurat} objects using the decontaminated counts,
#' returning a comprehensive list of all objects generated during the process.
#'
#' @param prep_output A structured list containing \code{sample_names}, \code{soup_list}, \code{seurat_for_clustering}, and \code{counts_lists}. Typically the direct output of \code{prepare_soupx_inputs()}.
#' @param multiFac Numeric. A percentage to artificially add to the auto-estimated contamination fraction (\code{rho}). Default is 0.
#' @param manual_contam Character vector. An optional list of specific sample names to selectively apply the \code{multiFac} adjustment to. Default is an empty list.
#' @param pCut Numeric. The p-value threshold used for identifying cells expressing genes above background levels when \code{methods = "soupOnly"}. Default is 0.01.
#' @param methods Character. The method to use for count adjustment passed to \code{SoupX::adjustCounts()}. Options include "subtraction", "soupOnly", or "multinomial". Default is "subtraction".
#'
#' @return A structured, named list containing three top-level elements:
#' \itemize{
#'   \item \code{final_seurat}: A list of the final, initialized \code{Seurat} objects containing the background-corrected counts and baseline metadata (e.g., \code{mitoPercent}).
#'   \item \code{soup_objects}: A list of the updated \code{SoupChannel} objects with their calculated \code{rho} values.
#'   \item \code{seurat_clustering}: A list of the preliminary \code{Seurat} objects used to generate the high-resolution clusters for estimation.
#' }
#'
#' @export
#'
#' @examples
#' \dontrun{
#' # 1. Run the preparation phase
#' soupx_prep_data <- prepare_soupx_inputs(
#'   filtered_dir = "data/cellranger/filtered",
#'   raw_dir = "data/cellranger/raw"
#' )
#'
#' # 2. Execute the contamination removal and generate final Seurat objects
#' final_pipeline_output <- run_soupx_post_clustering(
#'   prep_output = soupx_prep_data,
#'   multiFac = 2,                 # Add 2% extra contamination penalty
#'   manual_contam = c("Donor_A"), # Only apply the penalty to Donor_A
#'   methods = "subtraction"
#' )
#'
#' # 3. Extract your final cleaned Seurat objects for downstream integration
#' my_clean_seurats <- final_pipeline_output$final_seurat
#' }
run_soupx_post_clustering <- function(
    prep_output,
    multiFac = 0,
    manual_contam = list(),
    pCut = 0.01,
    methods = "subtraction"       # optional: force ambient gene correction
) {
  sample_names <- prep_output$sample_names
  soup_list <- prep_output$soup_list
  seurat_for_clustering <- prep_output$seurat_for_clustering
  counts_filtered <- prep_output$counts_lists$filtered

  contamination_result <- estimate_contamination(
    soup_list = soup_list,
    seurat_list = seurat_for_clustering,
    cts_filtered_list = counts_filtered,
    sample_names = sample_names,
    mulFac = multiFac,
    manual_contam = manual_contam,
    methods = methods,
    pCut = pCut
  )

  final_seurat_list <- create_final_seurat(
    soup_list_all = contamination_result$soup_list_all,
    sample_names = sample_names
  )

  return(list(
    final_seurat = final_seurat_list,
    soup_objects = contamination_result$soup_list_all,
    seurat_clustering = seurat_for_clustering
  ))
}

