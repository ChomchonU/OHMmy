#' Create SoupChannel Objects for Ambient RNA Decontamination
#'
#' Batch initializes \code{SoupChannel} objects for multiple samples using lists of
#' raw (unfiltered) and filtered count matrices. This is a required preparation step
#' for the \code{SoupX} pipeline, which uses the empty droplets in the raw matrix
#' ("Table of Drops" or \code{tod}) to estimate the ambient RNA profile contaminating
#' the true cells in the filtered matrix ("Table of Cells" or \code{toc}).
#'
#' @param cts_raw_list A named list of raw sparse count matrices (containing all droplets), typically from the \code{raw} element of \code{load_counts()}.
#' @param cts_filtered_list A named list of filtered sparse count matrices (containing only called cells), typically from the \code{filtered} element of \code{load_counts()}.
#' @param sample_names Character vector. A list of sample identifiers used as keys to match the matrices in both lists and name the output list elements.
#'
#' @return A named list of \code{SoupChannel} objects, ready for downstream contamination fraction estimation and expression adjustment.
#'
#' @export
#'
#' @examples
#' \dontrun{
#' # Assuming you have loaded matrices using the previous pipeline function
#' counts_list <- load_counts(
#'   sample_names = my_samples,
#'   filtered_dir = "data/filtered_outputs",
#'   raw_dir = "data/raw_outputs"
#' )
#'
#' # Initialize the SoupChannels
#' soup_channels <- create_soup_channels(
#'   cts_raw_list = counts_list$raw,
#'   cts_filtered_list = counts_list$filtered,
#'   sample_names = my_samples
#' )
#'
#' # The result is a list ready for autoEstCont() and adjustCounts()
#' print(soup_channels[["Patient1"]])
#' }
create_soup_channels <- function(cts_raw_list, cts_filtered_list, sample_names) {
  soup_list <- list()
  cat("Creating SoupChannel objects:\n")
  pb <- txtProgressBar(min = 0, max = length(sample_names), style = 3)

  for (i in seq_along(sample_names)) {
    sample_name <- sample_names[i]
    sc <- SoupChannel(tod = cts_raw_list[[sample_name]], toc = cts_filtered_list[[sample_name]])
    soup_list[[sample_name]] <- sc
    setTxtProgressBar(pb, i)
  }
  close(pb)
  return(soup_list)
}


